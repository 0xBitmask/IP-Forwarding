#!/bin/bash
# Build a single-file executable installer for IP Forwarding.
#
# Usage:
#   ./build.sh
#   VERSION=1.2.3 ./build.sh
#
# Output:
#   dist/ip-forwarding
#   dist/ip-forwarding.sha256

set -euo pipefail

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
DIST_DIR="${DIST_DIR:-$ROOT_DIR/dist}"
VERSION="${VERSION:-1.0.0}"
OUT="$DIST_DIR/ip-forwarding"

for cmd in awk base64 sha256sum; do
    command -v "$cmd" >/dev/null 2>&1 || {
        echo "ERROR: required command not found: $cmd" >&2
        exit 1
    }
done

for file in config.conf ip_forward.sh install.sh uninstall.sh ip-forwarding.service; do
    [[ -f "$ROOT_DIR/$file" ]] || {
        echo "ERROR: missing source file: $file" >&2
        exit 1
    }
done

mkdir -p "$DIST_DIR"

TMP_FILE="$(mktemp)"
cleanup() {
    rm -f "$TMP_FILE"
}
trap cleanup EXIT

cat > "$TMP_FILE" <<'HEADER'
#!/bin/bash
# IP Forwarding - standalone installer and manager
# Generated by build.sh. Do not edit this file directly.
#
# Quick start:
#   chmod +x ip-forwarding
#   sudo ./ip-forwarding install
#
# After installation:
#   sudo ip-forwarding enable
#   sudo ip-forwarding status

set -euo pipefail

VERSION="__VERSION__"
PROGRAM="ip-forwarding"
INSTALL_DIR="/opt/ip_forwarding"
SERVICE_FILE="/etc/systemd/system/ip-forwarding.service"
SYSCTL_FILE="/etc/sysctl.d/99-ip-forwarding.conf"
BIN_LINK="/usr/local/bin/ip-forwarding"
MANAGED_COMMANDS="enable disable status advertise test"

RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
NC='\033[0m'

TMP_DIR=""
cleanup() {
    if [[ -n "$TMP_DIR" && -d "$TMP_DIR" ]]; then
        rm -rf "$TMP_DIR"
    fi
}
trap cleanup EXIT

die() {
    echo -e "${RED}ERROR: $*${NC}" >&2
    exit 1
}

need_root() {
    [[ $EUID -eq 0 ]] || die "Must run as root (use sudo)"
}

self_path() {
    local path="${BASH_SOURCE[0]}"
    if [[ "$path" != */* ]]; then
        path="$(command -v -- "$path" 2>/dev/null || true)"
    fi
    readlink -f "$path"
}

payload() {
    local name="$1"
    awk -v begin="__${name}_BEGIN__" -v end="__${name}_END__" '
        $0 == begin { copy = 1; next }
        $0 == end   { copy = 0 }
        copy        { print }
    ' "$(self_path)" | base64 -d
}

require_commands() {
    local cmd
    for cmd in awk base64 ip iptables systemctl sysctl; do
        command -v "$cmd" >/dev/null 2>&1 || die "Required command not found: $cmd"
    done
}

usage() {
    cat <<EOF
Usage: $PROGRAM <command>

Commands:
  install    Install IP Forwarding (run with sudo)
  uninstall  Remove IP Forwarding (run with sudo)
  enable     Enable IP forwarding from Tailscale to LAN
  disable    Disable IP forwarding
  status     Show current forwarding status
  advertise  Advertise the LAN subnet route to Tailscale
  test       Run a connectivity test
  version    Show version
  help       Show this help

Examples:
  sudo ./$PROGRAM install
  sudo $PROGRAM status
EOF
}

install_project() {
    need_root
    require_commands

    TMP_DIR="$(mktemp -d)"

    echo -e "${YELLOW}Installing IP Forwarding v${VERSION}...${NC}"

    payload SCRIPT > "$TMP_DIR/ip_forward.sh"
    payload UNINSTALL > "$TMP_DIR/uninstall.sh"
    payload SERVICE > "$TMP_DIR/ip-forwarding.service"
    payload CONFIG > "$TMP_DIR/config.conf"

    mkdir -p "$INSTALL_DIR"
    cp "$TMP_DIR/ip_forward.sh" "$INSTALL_DIR/ip_forward.sh"
    cp "$TMP_DIR/uninstall.sh" "$INSTALL_DIR/uninstall.sh"
    chmod 0755 "$INSTALL_DIR/ip_forward.sh" "$INSTALL_DIR/uninstall.sh"

    if [[ -f "$INSTALL_DIR/config.conf" ]]; then
        echo "  Keeping existing config: $INSTALL_DIR/config.conf"
    else
        cp "$TMP_DIR/config.conf" "$INSTALL_DIR/config.conf"
        chmod 0644 "$INSTALL_DIR/config.conf"
        echo "  Created config: $INSTALL_DIR/config.conf"
    fi

    cp "$TMP_DIR/ip-forwarding.service" "$SERVICE_FILE"

    mkdir -p "$(dirname "$SYSCTL_FILE")"
    cat > "$SYSCTL_FILE" <<'EOF'
net.ipv4.ip_forward = 1
EOF
    sysctl --system > /dev/null 2>&1 || true

    systemctl daemon-reload

    mkdir -p "$(dirname "$BIN_LINK")"
    ln -sfn "$INSTALL_DIR/ip_forward.sh" "$BIN_LINK"

    echo -e "${GREEN}Installation complete!${NC}"
    echo ""
    echo "Files installed to: $INSTALL_DIR"
    echo "Config file:        $INSTALL_DIR/config.conf"
    echo "Command:            $PROGRAM"
    echo ""
    echo "Next steps:"
    echo "  1. Edit config:    sudo nano $INSTALL_DIR/config.conf"
    echo "  2. Test:           sudo $PROGRAM test"
    echo "  3. Advertise:      sudo $PROGRAM advertise"
    echo "  4. Approve route:  https://login.tailscale.com/admin/machines"
    echo "  5. Enable at boot: sudo systemctl enable --now ip-forwarding"
    echo ""
    echo "On your laptop, accept routes with:"
    echo "  sudo tailscale up --accept-routes"
}

uninstall_project() {
    need_root

    if [[ -x "$INSTALL_DIR/uninstall.sh" ]]; then
        exec "$INSTALL_DIR/uninstall.sh"
    fi

    echo -e "${YELLOW}Uninstalling IP Forwarding...${NC}"
    systemctl stop ip-forwarding 2>/dev/null || true
    systemctl disable ip-forwarding 2>/dev/null || true
    rm -f "$SERVICE_FILE" "$SYSCTL_FILE" "$BIN_LINK"
    rm -rf "$INSTALL_DIR"
    systemctl daemon-reload
    sysctl --system > /dev/null 2>&1 || true
    echo -e "${GREEN}Uninstall complete.${NC}"
}

run_installed() {
    if [[ ! -x "$INSTALL_DIR/ip_forward.sh" ]]; then
        die "IP Forwarding is not installed. Run: sudo ./$PROGRAM install"
    fi
    exec "$INSTALL_DIR/ip_forward.sh" "$@"
}

case "${1:-}" in
    install)
        install_project
        ;;
    uninstall)
        uninstall_project
        ;;
    version|--version|-v)
        echo "$PROGRAM $VERSION"
        ;;
    help|--help|-h)
        usage
        ;;
    enable|disable|status|advertise|test)
        run_installed "$@"
        ;;
    *)
        usage
        exit 1
        ;;
esac

exit 0

# Embedded payloads. Everything below this line is data.
HEADER

sed -i "s|__VERSION__|${VERSION}|g" "$TMP_FILE"

emit_payload() {
    local name="$1"
    local file="$2"
    {
        printf '__%s_BEGIN__\n' "$name"
        base64 "$file"
        printf '__%s_END__\n' "$name"
    } >> "$TMP_FILE"
}

emit_payload CONFIG "$ROOT_DIR/config.conf"
emit_payload SCRIPT "$ROOT_DIR/ip_forward.sh"
emit_payload UNINSTALL "$ROOT_DIR/uninstall.sh"
emit_payload SERVICE "$ROOT_DIR/ip-forwarding.service"

cp "$TMP_FILE" "$OUT"
chmod 0755 "$OUT"

(
    cd "$DIST_DIR"
    sha256sum "$(basename "$OUT")" > "$(basename "$OUT").sha256"
)

echo "Built:    $OUT"
echo "Version:  $VERSION"
echo "Checksum: $OUT.sha256"
